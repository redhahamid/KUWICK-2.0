/**
 * EPF — THE THIRD SCHEDULE, TRANSCRIBED.
 *
 * SOURCE (Tier A): Employees Provident Fund Act 1991, Third Schedule, as in
 * force from 1 October 2025. Supplied by the account holder as
 * `third_schedule_from_1october2025.pdf`.
 *
 * THIS IS A LOOKUP TABLE, NOT A PERCENTAGE.
 *
 * Below RM20,000 a month the Schedule states the ringgit-and-sen contribution
 * for each wage band outright, and those figures are NOT `wages × 11%`. At
 * RM3,000.50 the Schedule says the employee pays RM330 and the employer
 * RM360; a percentage would say RM330.06 and RM360.06. Multiplying is wrong
 * by a few sen every month for every employee, which is precisely the sort of
 * error that survives for years because it looks right.
 *
 * Every band is stored in CENTS as [fromCents, toCents, employerCents,
 * employeeCents]. `from` is exclusive of the previous band's `to` in the
 * Schedule's own wording ("From 40.01 to 60.00"), so a band matches when
 * `fromCents <= wages <= toCents`.
 *
 * ABOVE RM20,000 the Schedule switches to a percentage, stated separately per
 * Part, and requires the TOTAL contribution to be rounded UP to the next
 * ringgit. That rounding is on the total, not on each share.
 *
 * The five Parts are the Schedule's own division. Parts B and D were deleted
 * by Act A1760/2025 and are deliberately absent rather than renumbered — a
 * renumbering would make this file disagree with the document it transcribes.
 */

/** [fromCents, toCents, employerCents, employeeCents] */
export type EpfBand = readonly [number, number, number, number];

export interface EpfPart {
  /** The Schedule's own letter. */
  readonly part: 'A' | 'C' | 'E' | 'F';
  readonly appliesTo: string;
  readonly bands: readonly EpfBand[];
  /** Rate applied to wages above the last band, as a percentage. */
  readonly aboveCeiling: { readonly employerPercent: number; readonly employeePercent: number };
}

